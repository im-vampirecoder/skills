"""Structure, IDs and self-containment levels for check_as_built.py. Python 3 stdlib only.

Each level returns findings as (severity, name, message, where).
"""

import re
from collections import Counter

from as_built_parse import (BACKTICK_RE, LABELS, cell, first_table, is_omitted, label_of,
                            parse_tables, path_citations, sid_citations, split_sections)

REQUIRED_CLAIMS = ("Scope", "Actors", "Functional", "Flows")
OPTIONAL_CLAIMS = ("Non-functional", "Business rules", "Errors", "State transitions", "Success criteria",
                   "Entities", "Screens", "Constraints & dependencies")
OTHER_SECTIONS = ("Confidence legend", "Sources", "Open questions", "Gaps & conflicts")
ID_COLUMNS = {"Functional": "FR", "Non-functional": "NFR", "Business rules": "BR", "Errors": "ERR",
              "Open questions": "OQ"}
EVIDENCE_SECTIONS = ("Entry points", "Validation", "Errors", "Rules and constants", "Entities",
                     "Cross-repo hops", "Gaps")
NAMED_ID_RE = re.compile(r"(?<![\w-])(FR|NFR|BR|ERR)-[A-Za-z0-9]")
ALIAS_RE = re.compile(r"\b(FR|NFR|BR|ERR|OQ)(\d+)\b")
DENY_RE = re.compile(r"\b(claude|anthropic|openai|chatgpt|gpt-\d\w*|copilot|codex|gemini|vc|code-to-srs|"
                     r"ai4ba|reverse[- ]engineer\w*|generated by|this skill|subagents?|llm)\b", re.I)
INVISIBLE_RE = re.compile("[\u00ad\u200b-\u200f\u202a-\u202e\u2060-\u2064\ufeff]")
SECRET_RE = re.compile(r"(?i)\b(password|passwd|secret|api[_-]?key|access[_-]?token|connection[_-]?string)"
                       r"(?:\s*=\s*|[\"']?\s*:\s*[\"'])[^\s\"'`|<>]{6,}")


def _row_checks(rows, where, sources, out):
    """Label and citation rules shared by every labelled table."""
    for row in rows:
        label, src, at = label_of(row), cell(row, "source"), f"{where}:{row['_line']}"
        if label is None:
            out.append(("error", "missing-label", f"label must be one of {' '.join(LABELS)}", at))
            continue
        cites = sid_citations(src) + path_citations(src)
        if label in ("✅", "🔵") and not cites:
            out.append(("error", "missing-citation", f"a {label} claim needs a source", at))
        if label == "🔵" and len(set(cites)) < 2:
            out.append(("error", "corroboration", "a 🔵 claim needs two or more independent sources", at))
        for n, _, _ in sid_citations(src):
            if n not in sources:
                out.append(("error", "unknown-source", f"S{n} is not in the Sources table", at))


def structure(pack):
    out, files, spec, meta = [], pack["files"], pack["spec"], pack["meta"]
    for name in ("spec.md", "evidence.md", "flows.md", "use-cases/index.md"):
        if name not in files:
            out.append(("error", "missing-file", f"{name} is required", name))
    if "spec.md" not in files:
        return out
    if meta.get("status") != "as-built":
        out.append(("error", "frontmatter", "status must be `as-built`", "spec.md"))
    if not re.fullmatch(r"FEATURE-[a-z0-9-]+", str(meta.get("feature_id", ""))):
        out.append(("error", "frontmatter", "feature_id must be FEATURE-<slug>", "spec.md"))
    for key in ("generated_at", "sources"):
        if not meta.get(key):
            out.append(("error", "frontmatter", f"{key} is required", "spec.md"))
    for name in (*REQUIRED_CLAIMS, *OPTIONAL_CLAIMS, *OTHER_SECTIONS):
        if name not in spec:
            out.append(("error", "missing-section", f"## {name} is missing", "spec.md"))
        elif not parse_tables(spec[name]) and not (name not in REQUIRED_CLAIMS and is_omitted(spec[name])):
            out.append(("error", "empty-section", f"## {name} needs a table" +
                        ("" if name in REQUIRED_CLAIMS else " or an `_Omitted: <reason>._` line"), "spec.md"))
    counts = Counter()
    for name in (*REQUIRED_CLAIMS, *OPTIONAL_CLAIMS):
        rows = first_table(spec.get(name, []))
        _row_checks(rows, "spec.md", pack["sources"], out)
        counts.update(LABELS[label_of(r)] for r in rows if label_of(r))
    for key in LABELS.values():
        if str(meta.get(key, "")) != str(counts[key]):
            out.append(("error", "label-count", f"frontmatter {key}: {meta.get(key)} but the spec has {counts[key]}",
                        "spec.md"))
    for name, needed_by in (("states.md", "State transitions"), ("erd.md", "Entities")):
        if name not in files and not is_omitted(spec.get(needed_by, [])):
            out.append(("error", "missing-file", f"{name} is required unless ## {needed_by} is omitted", name))
        for rows in parse_tables(list(enumerate(files.get(name, "").splitlines(), 1))):
            if rows and "label" in rows[0]:
                _row_checks(rows, name, pack["sources"], out)
    return out + _evidence(files.get("evidence.md", ""))


def _evidence(text):
    out, sections = [], split_sections(text)
    for name in EVIDENCE_SECTIONS:
        if text and name not in sections:
            out.append(("error", "missing-section", f"## {name} is missing", "evidence.md"))
    for name in ("Entry points", "Validation", "Rules and constants", "Entities"):
        for row in first_table(sections.get(name, [])):
            if not path_citations(" ".join(v for k, v in row.items() if k != "_line")):
                out.append(("error", "missing-citation", f"{name} row needs a path citation",
                            f"evidence.md:{row['_line']}"))
    for row in first_table(sections.get("Errors", [])):
        at = f"evidence.md:{row['_line']}"
        if not path_citations(cell(row, "throw")):
            out.append(("error", "missing-citation", "an error needs its throw site", at))
        wording = cell(row, "wording")
        if not (wording.startswith('"') and wording.endswith('"')) and "unresolved" not in wording.lower():
            out.append(("error", "unquoted-wording", "quote the exact wording, or write `unresolved`", at))
    hops = sections.get("Cross-repo hops", [])
    for row in first_table(hops):
        cites = path_citations(cell(row, "source (from)")) + path_citations(cell(row, "source (to)"))
        repos = {c[0].split("/")[1] for c in cites if c[0].count("/") >= 2}
        if len(cites) < 2 or len(repos) < 2:
            out.append(("error", "hop-evidence", "a cross-repo hop needs a citation in each of two submodules",
                        f"evidence.md:{row['_line']}"))
    if text and not first_table(hops) and not is_omitted(hops):
        out.append(("error", "empty-section", "## Cross-repo hops needs a table or `_No cross-repo hops: ..._`",
                    "evidence.md"))
    return out


def ids(pack):
    out, spec, defined = [], pack["spec"], {}
    for section, prefix in ID_COLUMNS.items():
        for row in first_table(spec.get(section, [])):
            value, at = cell(row, "id").strip(), f"spec.md:{row['_line']}"
            if not re.fullmatch(rf"{prefix}\d+", value):
                out.append(("error", "id-format", f"## {section} IDs are {prefix}1, {prefix}2, ... (got `{value}`)", at))
            elif value in defined:
                out.append(("error", "duplicate-id", f"{value} is defined twice", at))
            else:
                defined[value] = row
    for row in first_table(spec.get("Errors", [])):
        seen = cell(row, "the user sees", "user sees")
        if label_of(row) == "✅" and not (seen.startswith('"') and seen.endswith('"')):
            out.append(("error", "unresolved-wording", "a ✅ error shows quoted text; a bare key is 🟡 plus a gap",
                        f"spec.md:{row['_line']}"))
    for section, column in (("Business rules", "applies"), ("Errors", "for")):
        for row in first_table(spec.get(section, [])):
            for ref in re.findall(r"\b[A-Z]+\d+\b", cell(row, column)):
                if not ref.startswith("FR"):
                    out.append(("error", "bad-reference", f"`{ref}` must name an FR", f"spec.md:{row['_line']}"))
    for name, text in pack["files"].items():
        for n, line in enumerate(text.splitlines(), 1):
            if NAMED_ID_RE.search(line):
                out.append(("error", "named-id", "use local IDs (FR1, ERR1); named IDs come from the PRD review",
                            f"{name}:{n}"))
            for prefix, number in ALIAS_RE.findall(line):
                if f"{prefix}{number}" not in defined:
                    out.append(("error", "undefined-id", f"{prefix}{number} is not defined in spec.md", f"{name}:{n}"))
    oq = sum(1 for k in defined if k.startswith("OQ"))
    if str(pack["meta"].get("open_questions", "")) != str(oq):
        out.append(("error", "oq-count", f"frontmatter open_questions: {pack['meta'].get('open_questions')} "
                    f"but the spec has {oq}", "spec.md"))
    return out + _use_cases(pack)


def _use_cases(pack):
    out, files = [], pack["files"]
    listed = set()
    for row in first_table(list(enumerate(files.get("use-cases/index.md", "").splitlines(), 1))):
        target = re.search(r"\(([^)]+\.md)\)", cell(row, "file"))
        if not target or f"use-cases/{target.group(1)}" not in files:
            out.append(("error", "missing-use-case", f"index row links a file that doesn't exist: {cell(row, 'file')}",
                        f"use-cases/index.md:{row['_line']}"))
        else:
            listed.add(f"use-cases/{target.group(1)}")
    for name in files:
        if name.startswith("use-cases/uc-") and name not in listed:
            out.append(("error", "unlisted-use-case", f"{name} is not in use-cases/index.md", name))
    return out


def self_containment(pack):
    out = []
    for name, text in pack["files"].items():
        for n, line in enumerate(text.splitlines(), 1):
            if INVISIBLE_RE.search(line):
                out.append(("error", "invisible-char", "remove the invisible character", f"{name}:{n}"))
            prose = BACKTICK_RE.sub("", line)
            prose = re.sub(r"(?:[\w@.+-]+/)+[\w@.+-]+", "", prose)
            match = DENY_RE.search(prose)
            if match:
                out.append(("error", "tool-reference", f"output must not mention `{match.group(0)}`", f"{name}:{n}"))
            if SECRET_RE.search(line):
                out.append(("error", "secret", "a value that looks like a secret; cite the variable name only",
                            f"{name}:{n}"))
    return out

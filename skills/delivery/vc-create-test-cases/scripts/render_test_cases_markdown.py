"""Render test-cases.json into the Markdown files people review.

Usage:
  python3 render_test_cases_markdown.py DIR [--view analysis|scenarios|cases|all]

Writes analysis.md (Gate A), scenarios.md (Gate B) and test-cases.md (final)
into DIR. Never hand-edit them: change test-cases.json and render again, so
every format carries the same IDs, order, and step/expected pairs.
"""

import argparse
from pathlib import Path

from test_case_contract import CASES_FILE, active, gate_hash, load_json

VIEWS = {"analysis": ("analysis.md", "A"), "scenarios": ("scenarios.md", "B"),
         "cases": ("test-cases.md", "final")}


def _cell(value):
    if isinstance(value, list):
        value = ", ".join(str(v) for v in value) or "-"
    return str(value if value not in (None, "") else "-").replace("|", "\\|").replace("\n", " ")


def _table(headers, rows):
    lines = ["| " + " | ".join(headers) + " |", "|" + "---|" * len(headers)]
    lines += ["| " + " | ".join(_cell(v) for v in row) + " |" for row in rows]
    return lines


def _refs(item):
    return [f"{r.get('source_id')} {r.get('location')}" for r in item.get("source_refs", [])]


def _header(doc, view, title):
    _, gate = VIEWS[view]
    return ["---", f"feature_id: {doc.get('feature_id')}", f"view: {view}",
            f"gate: {gate}", f"content_hash: {gate_hash(doc, gate)}",
            "generated_from: test-cases.json", "---", "",
            f"# {title}: {doc.get('feature_id')}", "",
            "> Generated from test-cases.json. Edit the JSON and re-render; "
            "do not edit this file.", ""]


def render_analysis(doc):
    scope = doc.get("scope", {})
    out = _header(doc, "analysis", "Test Analysis")
    out += ["## Scope", "", scope.get("summary") or "-", "",
            f"- Stories: {_cell(scope.get('story_ids'))}",
            f"- Environment: {_cell(scope.get('environment'))}",
            f"- Roles: {_cell(scope.get('roles'))}",
            f"- Exclusions: {_cell(scope.get('exclusions'))}", "", "## Sources", ""]
    out += _table(["ID", "Type", "Path", "Access", "Revision", "Purpose"],
                  [[s["id"], s.get("type"), s.get("path"), s.get("access"),
                    s.get("revision"), s.get("purpose")] for s in active(doc.get("sources"))])
    out += ["", "## Rules", ""]
    out += _table(["ID", "Rule", "Status", "In scope", "Stories", "PRD IDs", "Sources"],
                  [[r["id"], r.get("statement"), r.get("status"),
                    "yes" if r.get("in_scope") else "no", r.get("story_ids"),
                    r.get("prd_ids"), _refs(r)]
                   for r in active(doc.get("requirements"))])
    out += ["", "## Questions", ""]
    out += _table(["ID", "Topic", "Question", "Rules", "Blocking", "Owner", "Status", "Resolution"],
                  [[q["id"], q.get("topic"), q.get("question"), q.get("requirement_ids"),
                    "yes" if q.get("blocking") else "no", q.get("owner"), q.get("status"),
                    q.get("resolution")] for q in active(doc.get("questions"))])
    out += ["", "## Risks", ""]
    out += _table(["ID", "Risk", "Rules", "Impact", "Likelihood", "Level", "Test focus"],
                  [[r["id"], r.get("description"), r.get("requirement_ids"), r.get("impact"),
                    r.get("likelihood"), r.get("level"), r.get("test_focus")]
                   for r in active(doc.get("risks"))])
    return out


def render_scenarios(doc):
    out = _header(doc, "scenarios", "Test Scenarios")
    out += _table(["ID", "Scenario", "Story", "Rules", "Risks", "Techniques", "Status"],
                  [[s["id"], s.get("title"), s.get("story_id"), s.get("requirement_ids"),
                    s.get("risk_ids"), s.get("techniques"), s.get("status")]
                   for s in active(doc.get("scenarios"))])
    return out


def _case_block(case):
    out = [f"### {case['id']}: {case.get('title')}", ""]
    out += _table(["Priority", "Risk", "Readiness", "Status", "Execution", "Rules", "Scenarios",
                   "ADO"],
                  [[case.get("priority"), case.get("risk_level"), case.get("readiness"),
                    case.get("status"), case.get("execution_status"),
                    case.get("requirement_ids"), case.get("scenario_ids"), case.get("ado_id")]])
    out += ["", "**Preconditions**", ""]
    out += [f"- {p}" for p in case.get("preconditions", [])] or ["- none"]
    data = case.get("test_data") or {}
    out += ["", "**Test data**", ""]
    out += [f"- `{key}`: {value}" for key, value in data.items()] or ["- none"]
    out += ["", "**Steps**", ""]
    out += _table(["#", "Action", "Expected result"],
                  [[s.get("number"), s.get("action"), s.get("expected")]
                   for s in case.get("steps", [])])
    if case.get("cleanup"):
        out += ["", "**Cleanup**", ""] + [f"- {c}" for c in case["cleanup"]]
    return out + [""]


def render_cases(doc):
    out = _header(doc, "cases", "Test Cases")
    cases = active(doc.get("test_cases"))
    out += ["## Coverage", ""]
    out += _table(["Rule", "Status", "Cases", "Reason"],
                  [[c["requirement_id"], c["status"], c["case_ids"], c.get("reason")]
                   for c in doc.get("coverage", [])])
    gaps = active(doc.get("gaps"))
    if gaps:
        out += ["", "## Gaps", ""]
        out += _table(["ID", "Gap", "Affects", "Status"],
                      [[g["id"], g.get("description"), g.get("affected_ids"), g.get("status")]
                       for g in gaps])
    if doc.get("quality_checks"):
        out += ["", "## Quality checks", ""]
        out += _table(["Check", "Result", "Details"],
                      [[q["name"], q["result"], q.get("details")] for q in doc["quality_checks"]])
    groups = {}
    for case in cases:
        groups.setdefault(case.get("story_id") or "Feature-level", []).append(case)
    for story, items in groups.items():
        out += ["", f"## {story}", ""]
        for case in items:
            out += _case_block(case)
    return out


RENDERERS = {"analysis": render_analysis, "scenarios": render_scenarios, "cases": render_cases}


def main():
    parser = argparse.ArgumentParser(description=__doc__,
                                     formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("dir")
    parser.add_argument("--view", choices=(*VIEWS, "all"), default="all")
    args = parser.parse_args()
    doc = load_json(Path(args.dir) / CASES_FILE)
    views = list(VIEWS) if args.view == "all" else [args.view]
    for view in views:
        path = Path(args.dir) / VIEWS[view][0]
        path.write_text("\n".join(RENDERERS[view](doc)).rstrip() + "\n", encoding="utf-8")
        print(f"wrote {path}")


if __name__ == "__main__":
    main()

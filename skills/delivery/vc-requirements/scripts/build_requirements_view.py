"""Rebuild artifacts/requirements-current.md from every feature PRD.

    python3 build_requirements_view.py --root <tracking-repo> [--stdout]

Per feature: every ID with type, priority, one-line summary, state and what
cites it. Coverage gaps (P0 FRs with no story, ERRs with no test case) are
listed at the top. The frozen-text baseline that `check` compares against is
kept in an HTML comment at the end. This is the only file the skill writes.
"""

import argparse
import json
import re
import sys
from datetime import date

from parse_requirement_ids import load_project
from requirement_state import (
    citations_by_id, coverage_gaps, frozen_reason, new_baseline, pending_supersessions,
    read_baseline, state_of, view_path,
)

SUMMARY_MAX = 90


def summary(text):
    text = re.sub(r"\s+", " ", text.replace("|", " ")).strip()
    return text if len(text) <= SUMMARY_MAX else text[: SUMMARY_MAX - 1].rstrip() + "…"


def cited_by(cites):
    groups = {}
    for c in cites:
        if c["kind"] == "prd":
            continue
        groups.setdefault(c["kind"], set()).add(c["file"].rsplit("/", 1)[-1])
    return "; ".join(f"{k}: {', '.join(sorted(v))}" for k, v in sorted(groups.items())) or "—"


def render(project, baseline):
    cited, pending = citations_by_id(project), pending_supersessions(project)
    no_story, no_test = coverage_gaps(project)
    out = [
        "# Requirements — current view",
        "",
        f"Generated by `/vc:requirements view` on {date.today().isoformat()}. "
        "Do not edit by hand: change the feature PRD, then rebuild.",
        "",
        "## Coverage gaps",
        "",
        "- P0 FRs with no story: " + (", ".join(no_story) or "none"),
        "- Error cases with no test case: " + (", ".join(no_test) or "none"),
        "",
    ]
    for feature in sorted(project["features"], key=lambda f: f["slug"]):
        out += [f"## FEATURE-{feature['slug']} ({feature['status']})", ""]
        if feature["open_markers"]:
            out += [f"{feature['open_markers']} open `[NEEDS CLARIFICATION]` marker(s).", ""]
        if not feature["definitions"]:
            out += ["No requirement IDs yet (run `/vc:prd migrate` for an older PRD).", ""]
            continue
        out += ["| ID | Type | Priority | Summary | State | Frozen | Cited by |", "|---|---|---|---|---|---|---|"]
        for d in feature["definitions"]:
            text = summary(d["text"])
            if d["clarifications"]:
                text += f" (clarified {len(d['clarifications'])}x, latest {d['clarifications'][-1]['date']})"
            out.append(
                f"| {d['id']} | {d['type']} | {d['priority'] or '—'} | {text} | {state_of(feature, d, pending)} "
                f"| {frozen_reason(feature, d) or 'no'} | {cited_by(cited.get(d['id'], []))} |"
            )
        out.append("")
    out.append(f"<!-- vc-frozen-baseline {json.dumps(baseline, sort_keys=True)} -->")
    return "\n".join(out) + "\n"


def main():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--root", default=".")
    parser.add_argument("--stdout", action="store_true", help="print instead of writing the file")
    args = parser.parse_args()
    project = load_project(args.root)
    text = render(project, new_baseline(project, read_baseline(args.root)))
    if args.stdout:
        sys.stdout.write(text)
        return 0
    path = view_path(args.root)
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text, encoding="utf-8")
    ids = sum(len(f["definitions"]) for f in project["features"])
    print(f"wrote {path} ({len(project['features'])} features, {ids} IDs)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
